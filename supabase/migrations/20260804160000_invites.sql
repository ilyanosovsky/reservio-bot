-- Приглашения игроков: одноразовые коды для привязки Telegram-чата к профилю.
--
-- ВНИМАНИЕ: 20260730123000, 20260730140000, 20260731110000, 20260801110000 и
-- 20260804140000 уже применены — их редактировать нельзя, любая правка схемы
-- едет отдельной миграцией (этой).
--
-- Зачем таблица. Авторизация бота — allowlist telegram_chat_id -> профиль
-- (CLAUDE.md → «Мультипрофили»), и чужому чату бот обязан молчать полностью.
-- Значит, новый игрок не может «представиться» боту сам: пока его chat_id не
-- лежит в profiles, любое его сообщение уходит в тишину, а узнать chat_id
-- заранее неоткуда. Приглашение — единственный мост: админ заводит профиль
-- мастером в боте, бот выдаёт код, игрок открывает ссылку
-- https://t.me/<bot>?start=inv_<code>, и бот привязывает его чат к профилю.
--
-- Это ЕДИНСТВЕННОЕ исключение из инварианта тишины, поэтому код обязан быть
-- неугадываемым и сгораемым: 16 случайных байт crypto.randomBytes = 32 hex
-- (128 бит) и отметка used_at, после которой код мёртв навсегда.
--
-- Одноразовость держится не кодом на TypeScript, а этой таблицей:
-- InvitesRepo.claim делает ОДИН
--   update profile_invites set used_at = now where code = $1 and used_at is null
-- и смотрит, изменилась ли строка. Postgres сериализует конкурирующие update'ы
-- одной строки: проигравший перечитывает её уже под блокировкой, видит
-- заполненный used_at и не подходит под условие — то есть двойной тап по ссылке
-- (или гонка двух разных чатов за один код) даёт ровно ОДНУ привязку.
-- Связка «сначала select, потом update» такой гарантии не даёт вообще.
--
-- Читает/пишет только src/core/repos.ts (InvitesRepo, PostgREST через fetch,
-- ключ SUPABASE_SERVICE_ROLE_KEY). Тот же DDL продублирован в
-- docs/supabase-schema.sql (путь без CLI: SQL Editor -> вставить -> Run) —
-- держать файлы в синхроне.

create table if not exists public.profile_invites (
  -- Код — он же первичный ключ, он же секрет: 32 hex-символа из
  -- crypto.randomBytes(16) (см. InvitesRepo.create). Перебирать такое по одному
  -- коду на сообщение в Telegram бессмысленно.
  code       text primary key,
  -- Кого пустит код. Профиль удалили — его приглашения умирают вместе с ним:
  -- иначе остался бы живой код, ведущий в никуда (а привязать его будет не к
  -- чему, и «единственное исключение из тишины» превратилось бы в дыру).
  profile_id text not null references public.profiles (id) on delete cascade,
  created_at text not null default to_char(now() at time zone 'Asia/Tbilisi', 'YYYY-MM-DD"T"HH24:MI:SS"+04:00"'),
  -- null = код ещё не использован. Иначе — момент погашения, ISO с явным
  -- +04:00, как все отметки времени в проекте (text, а не timestamptz: state
  -- хранит строки ровно так, как их видит бот).
  used_at    text
);

-- Под каскад удаления профиля и под разбор «какие коды я выдавал этому игроку».
create index if not exists profile_invites_profile_idx on public.profile_invites (profile_id);

-- --- Доступ ----------------------------------------------------------------
-- Здесь лежат ЖИВЫЕ коды доступа к боту: утечка одного непогашенного кода = чужая
-- привязка к профилю игрока. Барьера, как и у остальных таблиц, два независимых:
-- RLS без единой политики и отзыв грантов у публичных ролей (anon-ключ публичен).
-- service_role это не трогает — у него bypassrls.
alter table public.profile_invites enable row level security;
revoke all on table public.profile_invites from anon, authenticated;

-- PostgREST кэширует схему: после ручного прогона в SQL Editor кэш может
-- отстать и репозиторий пожалуется на PGRST205 «Could not find the table».
notify pgrst, 'reload schema';
